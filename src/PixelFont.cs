        public static bool Pixel(char c, int x, int y)
        {
            string[] rows;
            if (!Glyphs.TryGetValue(c, out rows))
                rows = Glyphs['?'];
            return rows[y][x] == '#';
        }

        // Upper case, accents dropped, anything without a glyph becomes '?'.
        public static string Normalize(string text)
        {
            if (string.IsNullOrEmpty(text))
                return "";
            var sb = new StringBuilder(text.Length);
            foreach (char raw in text.ToUpperInvariant())
            {
                char c = raw;
                char plain;
                if (Plain.TryGetValue(c, out plain))
                    c = plain;
                if (c == '\t' || c == '\n' || c == '\r' || c == '\u00A0')
                    c = ' ';
                sb.Append(Glyphs.ContainsKey(c) ? c : '?');
            }
            return sb.ToString();
        }

        public static int Measure(string text, int scale)
        {
            if (string.IsNullOrEmpty(text))
                return 0;
            return (text.Length * Advance - 1) * scale;
        }
